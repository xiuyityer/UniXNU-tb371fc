#ifndef TB371FC_TOUCH_BOARD_H
#define TB371FC_TOUCH_BOARD_H

#include <stdint.h>

/* TB371FC FDT: SPI SE14, QUP wrapper 2, apps-SMMU stream 0x63. */
#define TB371FC_TOUCH_SE_BASE 0x00880000ULL
#define TB371FC_TOUCH_SE_SIZE 0x00004000ULL
#define TB371FC_TOUCH_QUP_BASE 0x008c0000ULL
#define TB371FC_TOUCH_QUP_SIZE 0x00002000ULL
#define TB371FC_TOUCH_SMMU_SID 0x63u
#define TB371FC_TOUCH_SMMU_BASE 0x15000000ULL
#define TB371FC_TOUCH_SMMU_SIZE 0x00100000ULL

/* SM8250 GCC: wrapper-2 S0; the board FDT caps SPI at 9.6 MHz. */
#define TB371FC_TOUCH_GCC_BASE 0x00100000ULL
#define TB371FC_TOUCH_GCC_VOTE 0x00052010u
#define TB371FC_TOUCH_GCC_VOTE_MASK 0x1fu
#define TB371FC_TOUCH_S0_CBCR 0x0001e00cu
#define TB371FC_TOUCH_M_AHB_CBCR 0x0001e004u
#define TB371FC_TOUCH_S_AHB_CBCR 0x0001e008u
#define TB371FC_TOUCH_CORE_CBCR 0x00023270u
#define TB371FC_TOUCH_CORE_2X_CBCR 0x00023278u
#define TB371FC_TOUCH_S0_RCG 0x0001e010u
#define TB371FC_TOUCH_SPI_MAX_HZ 9600000u

/* FDT pinctrl: GPIO40-43 QUP14, 6 mA, bias disabled. */
#define TB371FC_TOUCH_TLMM_BASE 0x0f000000ULL
#define TB371FC_TOUCH_GPIO_SPI_FIRST 40u
#define TB371FC_TOUCH_GPIO_SPI_COUNT 4u
#define TB371FC_TOUCH_GPIO_RESET 56u
#define TB371FC_TOUCH_GPIO_IRQ 68u
#define TB371FC_TOUCH_GPIO_PANEL_ID 82u
#define TB371FC_TOUCH_RESET_ACTIVE_LOW 1u
#define TB371FC_TOUCH_IRQ_RISING_EDGE 1u
#define TB371FC_TOUCH_QUP14_FUNC 1u
#define TB371FC_TOUCH_DRIVE_6MA 2u
#define TB371FC_TOUCH_GPIO_STRIDE 0x1000u
#define TB371FC_TOUCH_TILE_NORTH 0x900000u
#define TB371FC_TOUCH_TILE_SOUTH 0x500000u

static inline uint32_t tb371fc_touch_tlmm_tile(unsigned gpio)
{
  if ((gpio >= TB371FC_TOUCH_GPIO_SPI_FIRST &&
       gpio < TB371FC_TOUCH_GPIO_SPI_FIRST + TB371FC_TOUCH_GPIO_SPI_COUNT) ||
      gpio == TB371FC_TOUCH_GPIO_RESET)
    return TB371FC_TOUCH_TILE_SOUTH;
  if (gpio == TB371FC_TOUCH_GPIO_IRQ || gpio == TB371FC_TOUCH_GPIO_PANEL_ID)
    return TB371FC_TOUCH_TILE_NORTH;
  return UINT32_MAX;
}

static inline uint32_t tb371fc_touch_tlmm_ctl(unsigned gpio)
{
  if (tb371fc_touch_tlmm_tile(gpio) == UINT32_MAX)
    return UINT32_MAX;
  return tb371fc_touch_tlmm_tile(gpio) +
      gpio * TB371FC_TOUCH_GPIO_STRIDE;
}

#endif
